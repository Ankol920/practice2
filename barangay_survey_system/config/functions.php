/**
 * Every field recorded about a family member, in display order.
 *
 * The resident's own Profile Overview lists Courtesy Title, Full Name, First
 * Name, Middle Name, Surname, Extension Name and Gender, each in its own row.
 * A spouse or a character reference is a person too, so they are recorded and
 * shown the same way rather than as a bare name — one definition here keeps
 * the Add Resident form, the edit form, the approval screen and the resident's
 * profile from drifting apart.
 *
 * Full Name is deliberately absent: it is composed from the parts by
 * format_person_name() every time it is shown, never stored, so it cannot
 * disagree with the parts it is built from.
 */
function person_field_spec() {
    return [
        'courtesy_title' => [
            'label'    => 'Courtesy Title',
            'type'     => 'select',
            'required' => false,
            'options'  => courtesy_titles(),
        ],
        'first_name' => [
            'label' => 'First Name', 'type' => 'text', 'required' => true,
            'placeholder' => 'e.g. Juan', 'maxlength' => 50,
        ],
        'middle_name' => [
            'label' => 'Middle Name', 'type' => 'text', 'required' => false,
            'placeholder' => 'e.g. Santos', 'maxlength' => 50,
        ],
        'last_name' => [
            'label' => 'Surname', 'type' => 'text', 'required' => true,
            'placeholder' => 'e.g. Dela Cruz', 'maxlength' => 50,
        ],
        'name_extension' => [
            'label' => 'Extension Name', 'type' => 'text', 'required' => false,
            'placeholder' => 'e.g. Jr, Sr, III', 'maxlength' => 20,
        ],
        'gender' => [
            'label'    => 'Gender',
            'type'     => 'select',
            'required' => false,
            'options'  => gender_options(),
        ],
    ];
}

/** Just the keys, for looping over a stored row. */
function person_field_keys() {
    return array_keys(person_field_spec());
}

/**
 * Turn a stored value into the words shown on a profile.
 *
 * Gender is stored as a code, so it is mapped back through the same list the
 * form offered. Anything blank reads as N/A, matching how the resident's own
 * Profile Overview shows an empty extension name.
 */
function person_field_display($field, $value) {
    $value = trim((string)$value);
    if ($value === '') {
        return 'N/A';
    }
    if ($field === 'gender') {
        $options = gender_options();
        return $options[$value] ?? $value;
    }
    return $value;
}

/** Join the four name parts into one readable line. */
function format_person_name($parts, $with_title = true) {
    /* The resident's own Profile Overview shows Full Name with the courtesy
       title in front of it ("Mrs. Pangit Panget Pangot"), so a family member's
       full name is built the same way. Callers that want the bare name — a
       chart legend, say — can ask for it without. */
    $pieces = array_filter([
        $with_title ? trim((string)($parts['courtesy_title'] ?? '')) : '',
        trim((string)($parts['first_name'] ?? '')),
        trim((string)($parts['middle_name'] ?? '')),
        trim((string)($parts['last_name'] ?? '')),
        trim((string)($parts['name_extension'] ?? '')),
    ], function ($piece) {
        return $piece !== '';
    });

    return implode(' ', $pieces);
}

/** True when none of the four name parts carry anything. */
function person_name_is_empty($parts) {
    return format_person_name($parts) === '';
}

/**
 * Pull a repeatable set of names out of a posted form.
 *
 * The form posts them as name="children[0][last_name]" and so on. Rows left
 * entirely blank are dropped rather than stored as empty people, which is
 * what lets someone add a row, change their mind, and submit without having
 * to delete it first.
 */
function collect_person_rows($posted) {
    if (!is_array($posted)) {
        return [];
    }

    $rows = [];
    foreach ($posted as $row) {
        if (!is_array($row)) {
            continue;
        }

        $entry = [];
        foreach (person_field_keys() as $part) {
            $entry[$part] = trim((string)($row[$part] ?? ''));
        }

        /* "Others" is a prompt, not a title. Whatever was typed into the box
           beside it is the value that gets stored, so nobody ends up recorded
           with the literal word Others as their courtesy title. */
        $entry['courtesy_title'] = resolve_courtesy_title(
            $entry['courtesy_title'],
            trim((string)($row['courtesy_title_other'] ?? ''))
        );

        if (!person_name_is_empty($entry)) {
            $rows[] = $entry;
        }
    }

    return $rows;
}

/**
 * Check a set of names for the parts that must be filled in.
 *
 * Returns a list of complaints, empty when everything is in order. Surname
 * and first name are required on any row that exists at all; a middle name or
 * an extension is nobody's business to insist on.
 */
function person_rows_errors($rows, $noun) {
    $errors = [];

    foreach ($rows as $index => $row) {
        $position = $index + 1;
        foreach (person_field_spec() as $part => $spec) {
            if (!empty($spec['required']) && trim((string)($row[$part] ?? '')) === '') {
                $errors[] = $noun . ' ' . $position . ' needs a ' . strtolower($spec['label']) . '.';
            }
        }
    }

    return $errors;
}

/** Save a set of names, replacing whatever was stored before. */
function replace_person_rows($conn, $table, $resident_id, $rows) {
    $allowed = ['resident_children', 'resident_character_references'];
    if (!in_array($table, $allowed, true)) {
        return;
    }

    $delete = $conn->prepare("DELETE FROM {$table} WHERE resident_id = ?");
    $delete->bind_param('i', $resident_id);
    $delete->execute();
    $delete->close();

    if (empty($rows)) {
        return;
    }

    $insert = $conn->prepare("
        INSERT INTO {$table}
            (resident_id, courtesy_title, first_name, middle_name, last_name, name_extension, gender, display_order)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
    ");

    foreach ($rows as $order => $row) {
        // Bound through locals: bind_param takes them by reference, and array
        // elements cannot be passed that way.
        $courtesy  = (string)($row['courtesy_title'] ?? '');
        $first     = (string)($row['first_name'] ?? '');
        $middle    = (string)($row['middle_name'] ?? '');
        $last      = (string)($row['last_name'] ?? '');
        $extension = (string)($row['name_extension'] ?? '');
        $gender    = (string)($row['gender'] ?? '');
        $position  = (int)$order;

        $insert->bind_param(
            'issssssi',
            $resident_id, $courtesy, $first, $middle, $last, $extension, $gender, $position
        );
        $insert->execute();
    }

    $insert->close();
}

/** Read a set of names back, in the order they were entered. */
function fetch_person_rows($conn, $table, $resident_id) {
    $allowed = ['resident_children', 'resident_character_references'];
    if (!in_array($table, $allowed, true)) {
        return [];
    }

    $stmt = $conn->prepare("
        SELECT courtesy_title, first_name, middle_name, last_name, name_extension, gender
        FROM {$table} WHERE resident_id = ?
        ORDER BY display_order, created_at
    ");
    $stmt->bind_param('i', $resident_id);
    $stmt->execute();
    $rows = $stmt->get_result()->fetch_all(MYSQLI_ASSOC);
    $stmt->close();

    return $rows;
}

/**
 * Philippine landline formats accepted for the household hotline.
 *
 * Metro Manila numbers are eight digits behind an 8, written either bare or
 * with the (02) area code. Provincial numbers carry a two- or three-digit
 * area code in brackets. Mobile numbers are deliberately allowed too: plenty
 * of households have no landline at all.
 */
function hotline_number_pattern() {
    return '^((\(02\)|02)\s?8\d{3}[- ]?\d{4}'      // Metro Manila with the area code
         . '|8\d{3}[- ]?\d{4}'                      // Metro Manila, bare
         . '|\(0\d{2,3}\)\s?\d{3}[- ]?\d{4}'        // provincial, e.g. (045) 123-4567
         . '|09\d{2}[- ]?\d{3}[- ]?\d{4})$';        // mobile
}

/**
 * The guidance shown under the hotline field, and in the error when the
 * number does not match.
 *
 * The pattern still accepts a mobile number, since plenty of households have
 * no landline — it is simply not advertised here, because the field asks for
 * the household's hotline and a landline is what is wanted.
 */
function hotline_format_hint() {
    return 'Metro Manila: 8XXX-YYYY or (02) 8XXX-YYYY · Provincial: (0XX) XXX-YYYY, '
         . 'for example Pampanga (045) 123-4567.';
}
