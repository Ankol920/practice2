/**
 * Breaks the time between two dates into whole years, months and days.
 * Returns null when the start date is missing, unparseable, or in the future.
 */
function residency_duration($start_date, $as_of = null) {
    $start_date = trim((string)$start_date);
    if ($start_date === '') {
        return null;
    }
    $start = DateTime::createFromFormat('Y-m-d', $start_date);
    if (!$start || $start->format('Y-m-d') !== $start_date) {
        return null;
    }
    $start->setTime(0, 0);

    $now = $as_of ? new DateTime($as_of) : new DateTime();
    $now->setTime(0, 0);
    if ($start > $now) {
        return null;
    }

    $diff = $start->diff($now);
    return [
        'years'         => (int)$diff->y,
        'months'        => (int)$diff->m,
        'days'          => (int)$diff->d,
        'total_months'  => (int)($diff->y * 12 + $diff->m),
    ];
}

/** "1 year, 2 months and 5 days" - for showing the staff member the total. */
function format_residency_duration(array $duration) {
    $parts = [];
    if ($duration['years'])  { $parts[] = $duration['years'] . ' year' . ($duration['years'] === 1 ? '' : 's'); }
    if ($duration['months']) { $parts[] = $duration['months'] . ' month' . ($duration['months'] === 1 ? '' : 's'); }
    if ($duration['days'])   { $parts[] = $duration['days'] . ' day' . ($duration['days'] === 1 ? '' : 's'); }

    if (!$parts) {
        return 'less than a day';
    }
    if (count($parts) === 1) {
        return $parts[0];
    }
    $last = array_pop($parts);
    return implode(', ', $parts) . ' and ' . $last;
}

/**
 * Turns one login_history row into the label shown in Login Activity.
 *
 * login_history only records 'staff' or 'resident'. That hides the two
 * distinctions the barangay actually cares about: whether a staff sign-in
 * was an administrator, and whether a resident is permanent or temporary.
 * The role and residency status are joined in by the caller and resolved
 * here so the dashboard panel and the full list never disagree.
 */
function login_type_label(array $row) {
    // Prefer the role captured at the time of the event; fall back to the
    // live record for rows written before that column existed.
    $stored = trim((string)($row['account_role'] ?? ''));
    if ($stored !== '') {
        $map = [
            'Admin'              => ['pill' => 'db-pill-admin',     'badge' => 'badge-admin'],
            'Staff'              => ['pill' => 'db-pill-staff',     'badge' => 'badge-staff'],
            'Permanent Resident' => ['pill' => 'db-pill-permanent', 'badge' => 'badge-permanent'],
            'Temporary Resident' => ['pill' => 'db-pill-temporary', 'badge' => 'badge-temporary'],
        ];
        if (isset($map[$stored])) {
            return ['text' => $stored] + $map[$stored];
        }
    }

    if (($row['user_type'] ?? '') === 'staff') {
        $is_admin = strtolower(trim((string)($row['staff_role'] ?? ''))) === 'admin';
        return $is_admin
            ? ['text' => 'Admin', 'pill' => 'db-pill-admin', 'badge' => 'badge-admin']
            : ['text' => 'Staff', 'pill' => 'db-pill-staff', 'badge' => 'badge-staff'];
    }

    $temporary = strtolower(trim((string)($row['residency_status'] ?? 'permanent'))) === 'temporary';
    return $temporary
        ? ['text' => 'Temporary Resident', 'pill' => 'db-pill-temporary', 'badge' => 'badge-temporary']
        : ['text' => 'Permanent Resident', 'pill' => 'db-pill-permanent', 'badge' => 'badge-permanent'];
}

/** True when the signed-in staff member holds the Admin role. */
function staff_is_admin() {
    return strtolower(trim($_SESSION['staff_role'] ?? '')) === 'admin';
}

/** Set a one-shot message shown after a redirect. */
function set_flash($key, $value) {
    $_SESSION['flash_' . $key] = $value;
}

/** Read and clear a one-shot message. */
function get_flash($key) {
    if (!isset($_SESSION['flash_' . $key])) {
        return '';
    }
    $value = $_SESSION['flash_' . $key];
    unset($_SESSION['flash_' . $key]);
    return $value;
}

/** Require an active staff session with the Admin role; otherwise deny access. */
function require_admin_login() {
    require_staff_login();
    if (!staff_is_admin()) {
        http_response_code(403);
        require_once __DIR__ . '/../includes/header_staff.php';
        echo '<div class="card"><div class="alert alert-error">Access denied. Only Admin accounts can manage staff accounts.</div></div>';
        require_once __DIR__ . '/../includes/footer.php';
        exit;
    }
}

/** Record a login event (optional Login History table). */
function log_login($conn, $user_type, $user_id) {
    log_account_event($conn, $user_type, $user_id, 'login');
}

/** Recorded when someone signs out, so the admin can see both sides. */
function log_logout($conn, $user_type, $user_id) {
    log_account_event($conn, $user_type, $user_id, 'logout');
}

/**
 * Writes one row to login_history.
 *
 * The account's role at that moment is stored alongside it - Admin, Staff,
 * Permanent Resident or Temporary Resident. Resolving it later from the
 * live record would relabel old rows whenever someone's status changed,
 * which would make the history lie about what happened.
 */
function log_account_event($conn, $user_type, $user_id, $event) {
    $user_type = $user_type === 'staff' ? 'staff' : 'resident';
    $event = $event === 'logout' ? 'logout' : 'login';
    $user_id = (int)$user_id;
    $ip = $_SERVER['REMOTE_ADDR'] ?? 'unknown';

    $role = null;
    if ($user_type === 'staff') {
        $q = $conn->prepare("SELECT role FROM staff WHERE staff_id = ? LIMIT 1");
        $q->bind_param('i', $user_id);
        $q->execute();
        $row = $q->get_result()->fetch_assoc();
        $q->close();
        $role = (strtolower(trim((string)($row['role'] ?? ''))) === 'admin') ? 'Admin' : 'Staff';
    } else {
        $q = $conn->prepare("SELECT residency_status FROM residents WHERE resident_id = ? LIMIT 1");
        $q->bind_param('i', $user_id);
        $q->execute();
        $row = $q->get_result()->fetch_assoc();
        $q->close();
        $role = (strtolower(trim((string)($row['residency_status'] ?? 'permanent'))) === 'temporary')
            ? 'Temporary Resident' : 'Permanent Resident';
    }

    $stmt = $conn->prepare("INSERT INTO login_history (user_type, user_id, ip_address, event, account_role) VALUES (?, ?, ?, ?, ?)");
    $stmt->bind_param('sisss', $user_type, $user_id, $ip, $event, $role);
    $stmt->execute();
    $stmt->close();
}

/**
 * Single source of truth for the password policy.
 *
 * Both the on-screen requirement list and the server-side check read from
 * this array, so the rules shown to the resident can never drift out of
 * sync with the rules actually enforced.
 *
 * Each entry: key => [human-readable label, test callback]
 */
function password_rules() {
    return [
        'length' => ['At least 8 characters long', function ($pw) { return strlen($pw) >= 8; }],
        'upper'  => ['One uppercase letter (A-Z)',  function ($pw) { return (bool)preg_match('/[A-Z]/', $pw); }],
        'lower'  => ['One lowercase letter (a-z)',  function ($pw) { return (bool)preg_match('/[a-z]/', $pw); }],
        'number' => ['One number (0-9)',            function ($pw) { return (bool)preg_match('/[0-9]/', $pw); }],
        'space'  => ['No spaces',                   function ($pw) { return !preg_match('/\s/', $pw); }],
    ];
}

/** Returns the labels of every rule the given password fails. Empty array = valid. */
function password_policy_errors($password) {
    $failed = [];
    foreach (password_rules() as $rule) {
        list($label, $test) = $rule;
        if (!$test($password)) {
            $failed[] = $label;
        }
    }
    return $failed;
}

/** Compute whether a survey is currently open for responses. */
function survey_is_open($survey) {
    $today = date('Y-m-d');
    return $survey['status'] === 'active'
        && $survey['start_date'] <= $today
        && $survey['end_date'] >= $today;
}

