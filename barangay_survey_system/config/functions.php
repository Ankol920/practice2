/** Escape output to prevent XSS when echoing user data. */
function h($value) {
    return htmlspecialchars($value ?? '', ENT_QUOTES, 'UTF-8');
}

/** Ensure the residents table has the columns used for resident age and status. */
function ensure_resident_birthdate_column($conn) {
    if (!$conn instanceof mysqli) {
        return;
    }

    $result = $conn->query("SHOW COLUMNS FROM residents LIKE 'birthdate'");
    if ($result && $result->num_rows === 0) {
        $conn->query("ALTER TABLE residents ADD COLUMN birthdate date DEFAULT NULL AFTER contact_number");
    }

    $status_result = $conn->query("SHOW COLUMNS FROM residents LIKE 'residency_status'");
    if ($status_result && $status_result->num_rows === 0) {
        $conn->query("ALTER TABLE residents ADD COLUMN residency_status varchar(20) NOT NULL DEFAULT 'permanent' AFTER address");
    }
}

function ensure_resident_photo_column($conn) {
    if (!$conn instanceof mysqli) {
        return;
    }

    $result = $conn->query("SHOW COLUMNS FROM residents LIKE 'photo_path'");
    if ($result && $result->num_rows === 0) {
        $conn->query("ALTER TABLE residents ADD COLUMN photo_path varchar(255) DEFAULT NULL AFTER address");
    }
}

/** Calculate age from a birthdate. */
function calculate_age_from_birthdate($birthdate) {
    if ($birthdate === null || $birthdate === '') {
        return null;
    }

    $birth_date = DateTime::createFromFormat('Y-m-d', $birthdate);
    if (!$birth_date) {
        return null;
    }

    $today = new DateTime('today');
    return (int)$today->diff($birth_date)->y;
}

/** Format age for display. */
function get_resident_age_label($birthdate) {
    $age = calculate_age_from_birthdate($birthdate);
    return $age !== null ? $age . ' years old' : 'N/A';
}

