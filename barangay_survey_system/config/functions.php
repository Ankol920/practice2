/**
 * Resolve the courtesy title from a form.
 *
 * "Others" hands control to a free-text box, so the stored value is whatever
 * was typed rather than the literal word "Others".
 */
function resolve_courtesy_title($selected, $custom = '') {
    $selected = trim((string)$selected);
    $custom = trim((string)$custom);

    if ($selected === 'Others') {
        return substr($custom, 0, 20);
    }
    return in_array($selected, courtesy_titles(), true) ? $selected : '';
}

