/**
 * Longest sensible value for one part of an address. Stops a pasted
 * paragraph landing in the Household Number box.
 */
function address_field_maxlength($field) {
    $limits = [
        'household_number' => 30,
        'purok'            => 60,
        'street_highway'   => 120,
        'barangay'         => 80,
        'municipality'     => 80,
        'postal_code'      => 4,
        'province'         => 80,
    ];
    return $limits[$field] ?? 100;
}

/**
 * Returns the labels of any address parts that are over their limit,
 * so the caller can name them all in one error message.
 */
function overlong_address_fields(array $values, $prefix = '') {
    $over = [];
    foreach (address_field_names() as $field) {
        $value = trim((string)($values[$field] ?? ''));
        if ($value !== '' && mb_strlen($value) > address_field_maxlength($field)) {
            $over[] = $prefix . address_field_labels()[$field]
                . ' (max ' . address_field_maxlength($field) . ' characters)';
        }
    }
    return $over;
}

