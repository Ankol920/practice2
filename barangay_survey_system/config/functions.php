        'last_name'      => ['label' => 'Surname',        'required' => true,  'placeholder' => 'e.g. Dela Cruz'],
        'first_name'     => ['label' => 'First Name',     'required' => true,  'placeholder' => 'e.g. Juan'],
        'middle_name'    => ['label' => 'Middle Name',    'required' => false, 'placeholder' => 'e.g. Santos'],
        'name_extension' => ['label' => 'Extension Name', 'required' => false, 'placeholder' => 'e.g. Jr, Sr, III'],
