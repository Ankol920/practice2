/**
 * Onboarding gate for staff accounts.
 *
 * An account created by an administrator starts life with a temporary
 * password and an empty personal profile. Until the staff member has set
 * their own password and filled in their own details, every staff page
 * sends them back to the step they still owe. The gate lives inside
 * require_staff_login() so a new page cannot forget to apply it.
 *
 * Legacy accounts are unaffected: the migration defaults them to
 * is_first_login = 0 and profile_completed = 1.
 */
function require_staff_onboarding() {
    $conn = $GLOBALS['conn'] ?? null;
    if (!$conn instanceof mysqli) {
        return;
    }

    // The two onboarding pages themselves, plus logout, must stay reachable
    // or the redirect would loop.
    $exempt = ['change_password.php', 'complete_profile.php', 'logout.php'];
    if (in_array(basename($_SERVER['PHP_SELF']), $exempt, true)) {
        return;
    }

    $stmt = $conn->prepare("SELECT is_first_login, profile_completed FROM staff WHERE staff_id = ?");
    if (!$stmt) {
        return; // Columns not migrated yet — do not lock anyone out.
    }
    $stmt->bind_param('i', $_SESSION['staff_id']);
    $stmt->execute();
    $row = $stmt->get_result()->fetch_assoc();
    $stmt->close();

    if (!$row) {
        return;
    }
    if ((int)($row['is_first_login'] ?? 0) === 1) {
        redirect('change_password.php');
    }
    if ((int)($row['profile_completed'] ?? 1) === 0) {
        redirect('complete_profile.php');
    }
}

/**
 * True when a login identifier has the shape of a Resident Number.
 *
 * Resident Numbers are auto-generated by Resident Management in a fixed
 * format: R-YYYY-NNNN (see resident_management.php). Because the format is
 * reserved, it is what tells the login page which table an identifier belongs
 * to, instead of guessing by query order.
 */
function looks_like_resident_number($identifier) {
    return (bool)preg_match('/^R-\d{4}-\d{4,}$/i', trim($identifier));
}

/**
 * True when an identifier has the shape of a Staff Number: S-YYYY-NNNN.
 *
 * The Staff Number mirrors the Resident Number, one letter apart. It is the
 * permanent record key for a staff member and doubles as their temporary
 * password on the day the account is created.
 */
function looks_like_staff_number($identifier) {
    return (bool)preg_match('/^S-\d{4}-\d{4,}$/i', trim($identifier));
}

/**
 * Next number in the S-YYYY-NNNN series.
 *
 * The sequence is global rather than per-year, exactly like Resident
 * Numbers, so a number is never handed out twice even across a year
 * boundary.
 */
function generate_staff_number($conn) {
    $result = $conn->query("SELECT MAX(CAST(SUBSTRING_INDEX(staff_number, '-', -1) AS UNSIGNED)) AS max_seq FROM staff WHERE staff_number LIKE 'S-%'");
    $row = $result ? $result->fetch_assoc() : null;
    $next_seq = (int)($row['max_seq'] ?? 0) + 1;
    return 'S-' . date('Y') . '-' . str_pad($next_seq, 4, '0', STR_PAD_LEFT);
}

/**
 * House rules for a staff username.
 *
 * Returns the labels of every rule the username breaks, so the form can
 * name all of them at once instead of revealing one per submission.
 */
function staff_username_errors($username) {
    $username = trim($username);
    $failed = [];

    if (strlen($username) < 4 || strlen($username) > 30) {
        $failed[] = 'be 4 to 30 characters long';
    }
    if (!preg_match('/^[a-z]/', $username)) {
        $failed[] = 'start with a lowercase letter';
    }
    if (!preg_match('/^[a-z0-9._]+$/', $username)) {
        $failed[] = 'use only lowercase letters, numbers, periods, and underscores';
    }
    if (strpos($username, '..') !== false) {
        $failed[] = 'not contain two periods in a row';
    }
    if (substr($username, -1) === '.') {
        $failed[] = 'not end with a period';
    }

    return $failed;
}

/**
 * True when nothing else already answers to this username.
 *
 * Checked against staff usernames AND Resident Numbers, because both are
 * typed into the same login box. A collision there would make the account
 * type ambiguous.
 */
function staff_username_is_free($conn, $username, $exclude_staff_id = 0) {
    $stmt = $conn->prepare("SELECT 1 FROM staff WHERE username = ? AND staff_id <> ? LIMIT 1");
    $stmt->bind_param('si', $username, $exclude_staff_id);
    $stmt->execute();
    $taken = $stmt->get_result()->num_rows > 0;
    $stmt->close();

    if ($taken) {
        return false;
    }

    $stmt = $conn->prepare("SELECT 1 FROM residents WHERE resident_number = ? LIMIT 1");
    $stmt->bind_param('s', $username);
    $stmt->execute();
    $clash = $stmt->get_result()->num_rows > 0;
    $stmt->close();

    return !$clash;
}

/**
 * Suggest a username from a name: first initial + surname, lowercased.
 *
 * "Juliana Samara Bartolome" becomes jbartolome. A digit is appended on a
 * collision (jbartolome2). This is only a suggestion — the administrator
 * can overwrite it before saving, which is what hyphenated surnames and
 * near-duplicate names need.
 */
function suggest_staff_username($conn, $first_name, $last_name) {
    $initial = strtolower(preg_replace('/[^a-z]/i', '', $first_name));
    $surname = strtolower(preg_replace('/[^a-z]/i', '', $last_name));

    $base = ($initial !== '' ? substr($initial, 0, 1) : '') . $surname;
    if ($base === '') {
        $base = 'staff';
    }
    if (strlen($base) < 4) {
        $base = str_pad($base, 4, 'x');
    }
    $base = substr($base, 0, 26);

    $candidate = $base;
    $suffix = 1;
    while (!staff_username_is_free($conn, $candidate)) {
        $suffix++;
        $candidate = $base . $suffix;
    }

    return $candidate;
}

/** Assemble a display name from its parts, collapsing the gaps left by blanks. */
function build_full_name($first, $middle = '', $last = '', $extension = '') {
    $parts = array_filter([
        trim((string)$first),
        trim((string)$middle),
        trim((string)$last),
        trim((string)$extension),
    ], function ($part) { return $part !== ''; });

    return preg_replace('/\s+/', ' ', implode(' ', $parts));
}

/**
 * Join the seven permanent-address parts into one line.
 *
 * The parts are the source of truth — they are what an administrator reviews
 * when a change is requested — but a single string is what displays and
 * exports need, so both are kept and this is the one place they are joined.
 *
 * Order: Household Number, Purok, Street/Highway/Subdivision/Village,
 * Barangay, Municipality/City, Postal Code, Province.
 */
function build_address_line($household_number, $purok, $street_highway,
                            $barangay, $municipality, $postal_code, $province) {
    $parts = array_filter([
        trim((string)$household_number),
        trim((string)$purok),
        trim((string)$street_highway),
        trim((string)$barangay),
        trim((string)$municipality),
        trim((string)$postal_code),
        trim((string)$province),
    ], function ($part) { return $part !== ''; });

    return implode(', ', $parts);
}

/**
 * Rejects keyboard-mash placeholders such as "qwerty", "aaaa" or "....".
 * Deliberately loose: it only asks for a minimum length, at least one
 * letter, and more than one distinct character, so real short titles in
 * Filipino or English still pass.
 */
function valid_written_text($value, $min_length = 5) {
    $value = trim((string)$value);
    if (mb_strlen($value) < $min_length) {
        return false;
    }
    if (!preg_match('/\p{L}/u', $value)) {
        return false;
    }
    $distinct = count(array_unique(preg_split('//u', mb_strtolower($value), -1, PREG_SPLIT_NO_EMPTY)));
    if ($distinct < 3) {
        return false;
    }
    // Common keyboard runs, typed straight across a row.
    $flat = preg_replace('/[^a-z]/', '', mb_strtolower($value));
    foreach (['qwerty', 'asdf', 'zxcv', 'qwertyuiop', 'asdfgh'] as $mash) {
        if ($flat !== '' && strpos($mash, $flat) === 0) {
            return false;
        }
    }
    return true;
}

