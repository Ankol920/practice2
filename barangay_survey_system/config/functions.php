}

/**
 * The letter shown in the account chip when no profile photo is on file.
 *
 * Taken from the FIRST NAME rather than the display name. The display
 * name carries a courtesy title, so reading its first character would
 * put "M" on every Mr., Mrs., Ms. and Mx. in the barangay, and "E" on
 * an Engr. — the initial would identify the title, not the person.
 *
 * Accounts that predate the name-parts columns have no first_name (the
 * seeded "Barangay Health Officer" admin, for example). For those the
 * full name is used instead, with any leading courtesy title skipped
 * over so the same rule still holds.
 */
function account_initial($first_name, $display_name = '', $courtesy_title = '', $fallback = '?') {
    $first = trim((string)$first_name);

    if ($first === '') {
        $name = trim((string)$display_name);

        // Remove the stored title if it is glued to the front of the name.
        $title = trim((string)$courtesy_title);
        if ($title !== '' && stripos($name, $title) === 0) {
            $name = trim(substr($name, strlen($title)));
        }

        // Then walk the remaining words and take the first one that is not
        // itself a title, so a hand-typed "Engr Miguelito" still gives M.
        $titles = '/^(mr|mrs|ms|mx|dr|engr|ar|atty|hon|prof|rev|sr|jr|fr|sis|bro)$/i';
        foreach (preg_split('/\s+/', $name) as $word) {
            $word = trim($word, ".,-");
            if ($word === '' || preg_match($titles, $word)) {
                continue;
            }
            $first = $word;
            break;
        }
    }

    // Strip punctuation so a name such as "'Nong" yields N, not an apostrophe.
    $first = preg_replace('/[^\p{L}\p{N}]/u', '', $first);
    if ($first === '') {
        $first = $fallback;
    }

    return function_exists('mb_substr')
        ? mb_strtoupper(mb_substr($first, 0, 1, 'UTF-8'), 'UTF-8')
        : strtoupper(substr($first, 0, 1));
}

/**
 * True only when a stored photo path actually resolves to a file.
 *
 * A row can carry a photo_path whose file is gone — the uploads folder
 * is not part of the database, so restoring a dump onto a fresh copy of
 * the site leaves every path dangling. Without this check the chip
 * renders a broken image instead of falling back to the initial.
 */
function account_photo_exists($photo_path, $root_dir) {
    $photo_path = trim((string)$photo_path);
    if ($photo_path === '') {
        return false;
    }
    return is_file(rtrim($root_dir, '/') . '/' . ltrim($photo_path, '/'));
}

/**
 * Move a resident or staff account to the archive instead of destroying it.
 *
 * A hard DELETE on `residents` cascades into `responses`, so the account
 * and its entire survey history vanish together and no amount of care
 * afterwards brings them back. Archiving stamps four columns and leaves
 * everything else in place, which is what makes Restore possible.
 *
 * $table is not user input — it is one of two literals chosen by the
 * caller — but it is whitelisted anyway, because a helper that
 * interpolates a table name is exactly the kind of thing that later gets
 * called with a variable.
 */
function archive_account($conn, $table, $id, $staff_id, $staff_name, $reason = '') {
    $columns = [
        'residents' => 'resident_id',
        'staff'     => 'staff_id',
    ];
    if (!isset($columns[$table])) {
        return false;
    }
    $key = $columns[$table];
    $reason = substr(trim((string)$reason), 0, 255);

    $stmt = $conn->prepare("UPDATE `$table`
                               SET deleted_at = NOW(), deleted_by = ?, deleted_by_name = ?, delete_reason = ?
                             WHERE `$key` = ? AND deleted_at IS NULL");
    if (!$stmt) {
        return false;
    }
    $stmt->bind_param('issi', $staff_id, $staff_name, $reason, $id);
    $stmt->execute();
    $done = $stmt->affected_rows > 0;
    $stmt->close();

    return $done;
}

/** Put an archived account back. Clears the archive stamp, nothing else. */
function restore_account($conn, $table, $id) {
    $columns = [
        'residents' => 'resident_id',
        'staff'     => 'staff_id',
    ];
    if (!isset($columns[$table])) {
        return false;
    }
    $key = $columns[$table];

    $stmt = $conn->prepare("UPDATE `$table`
                               SET deleted_at = NULL, deleted_by = NULL, deleted_by_name = NULL, delete_reason = NULL
                             WHERE `$key` = ? AND deleted_at IS NOT NULL");
    if (!$stmt) {
        return false;
    }
    $stmt->bind_param('i', $id);
    $stmt->execute();
    $done = $stmt->affected_rows > 0;
    $stmt->close();

    return $done;
}

/**
 * How many administrators are still live.
 *
 * Archiving or deactivating the last one would leave a system nobody can
 * administer — including nobody who can restore the account that was just
 * archived.
 */
function active_admin_count($conn, $exclude_staff_id = 0) {
    $stmt = $conn->prepare("SELECT COUNT(*) c FROM staff
                             WHERE LOWER(TRIM(role)) = 'admin'
                               AND deleted_at IS NULL
                               AND is_active = 1
                               AND staff_id <> ?");
    if (!$stmt) {
        return 0;
    }
    $stmt->bind_param('i', $exclude_staff_id);
    $stmt->execute();
    $count = (int)$stmt->get_result()->fetch_assoc()['c'];
    $stmt->close();

    return $count;
}

